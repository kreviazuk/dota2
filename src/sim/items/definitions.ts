/** 查询单个物品定义 */
export function getItemDef(id: string): ItemDef | undefined {
  return ITEM_DEFINITIONS[id];
}

/** 获取全部物品定义 */
export function getAllItemDefs(): ItemDef[] {
  return Object.values(ITEM_DEFINITIONS);
}

/** 按类别过滤物品 */
export function getItemsByCategory(category: ItemCategory): ItemDef[] {
  return Object.values(ITEM_DEFINITIONS).filter((item) => item.category === category);
}

/** 获取合成配方详情 */
export function getRecipe(id: string): { components: string[]; recipeCost: number } | null {
  const item = ITEM_DEFINITIONS[id];
  if (!item || !item.components || item.components.length === 0) return null;
  return {
    components: [...item.components],
    recipeCost: item.recipeCost ?? 0,
  };
}

/** 判断是否为成品（需要合成的装备） */
export function isFinishedItem(id: string): boolean {
  const item = ITEM_DEFINITIONS[id];
  return !!(item && item.components && item.components.length > 0);
}

/** 递归计算单个物品的基础造价（由组件及卷轴递归计算） */
export function calculateItemCost(id: string): number {
  const item = ITEM_DEFINITIONS[id];
  if (!item) return 0;
  if (!item.components || item.components.length === 0) {
    return item.cost;
  }
  const compCost = item.components.reduce((sum, cId) => sum + calculateItemCost(cId), 0);
  return compCost + (item.recipeCost ?? 0);
}
